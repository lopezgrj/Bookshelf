export const languages = ["en", "es", "fr"];
export const messages = Object.fromEntries(languages.map((language, index) => [
  language, Object.fromEntries(Object.entries(labels).map(([key, values]) => [key, values[index]])),
]));

export function translate(language, key) {
  if (!messages[language] || !messages[language][key]) throw new Error(`Missing translation: ${language}.${key}`);
  return messages[language][key];
}
